<#
.SYNOPSIS
  Generates the synthetic sample data in samples/.

.DESCRIPTION
  Writes the complaint list samples/complaint-list.xlsx (sheet "Complaints")
  and one case folder per case under samples/case-folders. A case folder
  holds the case documents and, for the open cases, the report type marker
  (short.txt or long.txt). Batch numbers use the format
  SYN-LOT-<year><product letter><number>, so they cannot be mistaken for real
  ones. Two cases share one batch on purpose.
  All content is invented. Every file states in its first line that it is
  synthetic. The first 10 cases are a fixed scenario so that the prewritten
  demo answers (samples/demo-responses) match the data. With -Count above
  10 the script appends seeded random closed cases for load tests.
#>
[CmdletBinding()]
param(
    [int]$Count = 10,
    [int]$Seed = 2026,
    [string]$OutputPath
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Import-Module (Join-Path (Join-Path $root 'src') 'ComplaintDossier.psm1') -Force
if (-not $OutputPath) { $OutputPath = Join-Path $root 'samples' }

$notice = 'SYNTHETIC TEST DATA - generated by tools/New-SyntheticCases.ps1. Invented for demonstration; not a real complaint.'

$scenario = @(
    , @('SYN-2026-001', '2026-01-12', 'Packaging damage', 'Tablets', 'SYN-LOT-25A112', 'Minor', 'Closed', 'No', 'Outer carton dented on one corner. Blister intact, no tablets missing.')
    , @('SYN-2026-002', '2026-01-27', 'Label or print', 'Oral solution', 'SYN-LOT-25B041', 'Major', 'Closed', 'Yes', 'Expiry date on the bottle label partly illegible. Carton print is readable.')
    , @('SYN-2026-003', '2026-02-09', 'Tablet appearance', 'Tablets', 'SYN-LOT-26A003', 'Minor', 'Closed', 'Yes', 'Two tablets in one blister show small dark specks on the surface.')
    , @('SYN-2026-004', '2026-03-03', 'Packaging damage', 'Capsules', 'SYN-LOT-25C077', 'Minor', 'Closed', 'No', 'Blister foil torn at one cavity on arrival. Capsule present and intact.')
    , @('SYN-2026-005', '2026-03-18', 'Dosing device', 'Oral solution', 'SYN-LOT-26B006', 'Major', 'Open', 'No', 'Measuring cup missing from the carton.')
    , @('SYN-2026-006', '2026-04-08', 'Packaging damage', 'Tablets', 'SYN-LOT-26A011', 'Minor', 'Open', 'No', 'Carton crushed in transport. The shipping box was also damaged.')
    , @('SYN-2026-007', '2026-04-22', 'Foreign matter', 'Cream', 'SYN-LOT-26D002', 'Critical', 'Open', 'No', 'Customer reports a dark fibre in the cream after first opening of the tube. Sample requested.')
    , @('SYN-2026-008', '2026-05-06', 'Packaging damage', 'Capsules', 'SYN-LOT-26C009', 'Minor', 'Open', 'No', 'Two cartons in one shipment dented. Contents not affected.')
    , @('SYN-2026-009', '2026-05-20', 'Label or print', 'Tablets', 'SYN-LOT-26A019', 'Minor', 'Open', 'No', 'Patient leaflet missing from the carton.')
    , @('SYN-2026-010', '2026-06-02', 'Packaging damage', 'Tablets', 'SYN-LOT-26A019', 'Major', 'Open', 'Yes', 'Blister strip cracked across two cavities, one tablet broken. Customer asked for a call back on +49 30 5550 1234.')
)

$documents = @{
    'SYN-2026-001' = @{ 'intake-note.txt' = "Intake note for SYN-2026-001.`nReceived by phone. Customer sent a photo of the carton; the dent is on the corner, about 1 cm deep. Blister checked by the customer, all 20 tablets present.`nRetained sample: not needed." }
    'SYN-2026-006' = @{ 'transport-note.txt' = "Transport note for SYN-2026-006.`nShipping box arrived with a crushed corner and a torn tape seal. The carrier confirmed rough handling at the regional hub in week 14. Two other parcels from the same tour were reported damaged." }
    'SYN-2026-007' = @{
        'intake-note.txt'  = "Intake note for SYN-2026-007.`nCustomer found a dark fibre, about 3 mm long, on the surface of the cream right after opening a new tube. Tube was sealed before first use according to the customer. Photo received. Sample requested from the customer, not yet received."
        'lab-request.txt'  = "Lab request for SYN-2026-007.`nRequested tests: visual inspection of the returned tube, identification of the fibre (synthetic or natural), comparison with retained samples of the same batch (SYN-LOT-26D002). Status: waiting for the returned sample."
    }
    'SYN-2026-008' = @{ 'transport-note.txt' = "Transport note for SYN-2026-008.`nTwo cartons dented, outer shipping box intact. Packing list shows the cartons were at the top of the box under a heavier item." }
    'SYN-2026-010' = @{
        'customer-email.txt' = "Customer e-mail for SYN-2026-010 (copied into the case file).`nFrom: pat.example@example.org`nThe blister was already cracked when I opened the box. One tablet is broken in half. Please call me back on +49 30 5550 1234."
        'sample-check.txt'   = "Sample check for SYN-2026-010.`nReturned blister strip received on 2026-06-09. The crack runs across cavities 4 and 5. The tablet in cavity 4 is broken in two pieces, the tablet in cavity 5 is intact. The foil is sealed at all other cavities. The carton shows no crush marks.`nThe other two blister strips in the returned carton show no cracks.`nNot done yet: check of the blister foil lot used for this batch."
    }
}

# Report type markers for the open cases: the file name decides short or long report.
$markers = [ordered]@{
    'SYN-2026-005' = 'short.txt'
    'SYN-2026-006' = 'short.txt'
    'SYN-2026-007' = 'long.txt'
    'SYN-2026-008' = 'short.txt'
    'SYN-2026-009' = 'short.txt'
    'SYN-2026-010' = 'long.txt'
}

if ($Count -lt 1) { throw 'Count must be at least 1.' }
$cases = New-Object System.Collections.Generic.List[object]
for ($i = 0; $i -lt [math]::Min($Count, $scenario.Count); $i++) { $cases.Add($scenario[$i]) }
if ($Count -gt $scenario.Count) {
    $random = New-Object System.Random($Seed)
    $categories = 'Packaging damage', 'Label or print', 'Tablet appearance', 'Dosing device', 'Foreign matter', 'Leakage'
    $groups = 'Tablets', 'Capsules', 'Oral solution', 'Cream'
    $severities = 'Minor', 'Minor', 'Minor', 'Major', 'Critical'
    $batchLetters = @{ 'Tablets' = 'A'; 'Oral solution' = 'B'; 'Capsules' = 'C'; 'Cream' = 'D' }
    for ($i = $scenario.Count + 1; $i -le $Count; $i++) {
        $date = (Get-Date '2026-01-01').AddDays($random.Next(0, 181)).ToString('yyyy-MM-dd')
        $category = $categories[$random.Next($categories.Count)]
        $group = $groups[$random.Next($groups.Count)]
        $batch = 'SYN-LOT-26{0}{1:000}' -f $batchLetters[$group], $random.Next(1, 60)
        $cases.Add(@(('SYN-2026-{0:000}' -f $i), $date, $category, $group, $batch, $severities[$random.Next($severities.Count)], 'Closed', 'No', "Random synthetic case ($category)."))
    }
}

# ---- complaint-list.xlsx
$esc = { param($t) [Security.SecurityElement]::Escape([string]$t) }
$header = 'CaseId', 'ReceivedDate', 'Category', 'ProductGroup', 'Batch', 'Severity', 'Status', 'SampleReceived', 'Description'
$letters = 'A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I'
$rows = New-Object System.Text.StringBuilder
[void]$rows.Append("<row r=`"1`"><c r=`"A1`" t=`"inlineStr`" s=`"2`"><is><t>$(& $esc $notice)</t></is></c></row>")
[void]$rows.Append('<row r="2">' + ((0..8 | ForEach-Object { "<c r=`"$($letters[$_])2`" t=`"inlineStr`" s=`"2`"><is><t>$($header[$_])</t></is></c>" }) -join '') + '</row>')
$r = 3
foreach ($case in $cases) {
    $cells = for ($c = 0; $c -lt 9; $c++) {
        if ($c -eq 1) {
            $serial = [DateTime]::ParseExact($case[1], 'yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture).ToOADate()
            "<c r=`"B$r`" s=`"1`"><v>$serial</v></c>"
        } else {
            "<c r=`"$($letters[$c])$r`" t=`"inlineStr`"><is><t xml:space=`"preserve`">$(& $esc $case[$c])</t></is></c>"
        }
    }
    [void]$rows.Append("<row r=`"$r`">" + ($cells -join '') + '</row>')
    $r++
}
$ns = 'xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"'
$parts = [ordered]@{}
$parts['[Content_Types].xml'] = @'
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
<Override PartName="/xl/worksheets/sheet2.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
<Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>
</Types>
'@
$parts['_rels/.rels'] = @'
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/>
</Relationships>
'@
$parts['docProps/core.xml'] = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/">
<dc:title>SYNTHETIC complaint list</dc:title>
<dc:description>$(& $esc $notice)</dc:description>
<dc:creator>Complaint Dossier generator</dc:creator>
</cp:coreProperties>
"@
$parts['xl/workbook.xml'] = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook $ns><sheets><sheet name="Complaints" sheetId="1" r:id="rId1"/><sheet name="About" sheetId="2" r:id="rId2"/></sheets></workbook>
"@
$parts['xl/_rels/workbook.xml.rels'] = @'
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet2.xml"/>
<Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>
'@
$parts['xl/styles.xml'] = @'
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
<fonts count="2"><font><sz val="11"/><name val="Calibri"/></font><font><b/><sz val="11"/><name val="Calibri"/></font></fonts>
<fills count="2"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill></fills>
<borders count="1"><border><left/><right/><top/><bottom/><diagonal/></border></borders>
<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>
<cellXfs count="3"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/><xf numFmtId="14" fontId="0" fillId="0" borderId="0" xfId="0" applyNumberFormat="1"/><xf numFmtId="0" fontId="1" fillId="0" borderId="0" xfId="0" applyFont="1"/></cellXfs>
</styleSheet>
'@
$parts['xl/worksheets/sheet1.xml'] = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet $ns><cols><col min="1" max="1" width="15" customWidth="1"/><col min="2" max="2" width="13" customWidth="1"/><col min="3" max="3" width="19" customWidth="1"/><col min="4" max="4" width="13" customWidth="1"/><col min="5" max="5" width="16" customWidth="1"/><col min="6" max="8" width="14" customWidth="1"/><col min="9" max="9" width="90" customWidth="1"/></cols><sheetData>$($rows.ToString())</sheetData></worksheet>
"@
$parts['xl/worksheets/sheet2.xml'] = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet $ns><sheetData><row r="1"><c r="A1" t="inlineStr"><is><t>$(& $esc $notice)</t></is></c></row><row r="2"><c r="A2" t="inlineStr"><is><t>Case IDs, batch numbers (SYN-LOT-...), dates, products and texts are invented. Any resemblance to real complaints is accidental.</t></is></c></row></sheetData></worksheet>
"@

New-Item -ItemType Directory -Force -Path $OutputPath | Out-Null
New-ZipPackage -Path (Join-Path $OutputPath 'complaint-list.xlsx') -Parts $parts

# ---- case folders: documents, upload file, report type markers
$caseRoot = Join-Path $OutputPath 'case-folders'
foreach ($caseId in $documents.Keys) {
    if (@($cases | Where-Object { $_[0] -eq $caseId }).Count -eq 0) { continue }
    foreach ($name in $documents[$caseId].Keys) {
        Write-Utf8File (Join-Path (Join-Path $caseRoot $caseId) $name) ($notice + "`n`n" + $documents[$caseId][$name] + "`n")
    }
}
foreach ($caseId in $markers.Keys) {
    if (@($cases | Where-Object { $_[0] -eq $caseId }).Count -eq 0) { continue }
    $kind = $markers[$caseId].Replace('.txt', '')
    Write-Utf8File (Join-Path (Join-Path $caseRoot $caseId) $markers[$caseId]) ($notice + "`n`nReport type marker: this case gets a $kind report.`n")
}
if (@($cases | Where-Object { $_[0] -eq 'SYN-2026-006' }).Count) {
    # Uploaded to the Copilot chat in live mode (Copilot.Upload.Extensions); not inserted into the prompt.
    $csv = @"
# $notice
shipment,date,carrier_hub,cartons,damage_reported
SHP-0408-01,2026-04-06,regional hub B,12,yes
SHP-0408-02,2026-04-06,regional hub B,8,yes
SHP-0408-03,2026-04-06,regional hub B,10,no
SHP-0408-04,2026-04-06,regional hub A,9,no
SHP-0408-05,2026-04-07,regional hub B,11,yes
"@
    Write-Utf8File (Join-Path (Join-Path $caseRoot 'SYN-2026-006') 'shipment-log.csv') ($csv.Replace("`r`n", "`n") + "`n")
}
Write-Host "Wrote $($cases.Count) synthetic cases to $OutputPath"
